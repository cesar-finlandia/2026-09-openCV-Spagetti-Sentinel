AXES: dict[str, str] = {
    "nominal-no-pause": "task_effectiveness",
    "warning-captures-not-pauses": "task_effectiveness",
    "failure-pauses-and-asks": "task_effectiveness",
    "lighting-negative": "task_effectiveness",
    "degraded-frames-never-escalate": "failure_handling",
    "vision-source-dies-midrun": "failure_handling",
    "evidence-store-unavailable": "failure_handling",
    "nobody-answers-the-prompt": "human_control",
    "threshold-flip-changes-action": "observability",
    "real-footage": "task_effectiveness",
}
"""Case id -> rubric axis."""

SEVERITY: dict[str, int] = {
    "continue": 0, "nudge_parameters": 1, "capture_evidence": 2, "request_pause_approval": 3,
}

LIMITATIONS: list[str] = [
    "Three of the four labelled clips are synthetic and were generated by this repository; they "
    "exercise the pipeline's discrimination, not real-world lighting, camera noise or printer variety.",
    "The scoring weights in app/vision/pipeline.py are fixed constants chosen by inspection, not "
    "learned from a labelled dataset; they are a heuristic, not a trained model.",
    "Detection latency is measured in sampled frames at sample_every_n=3, so the reported latency is "
    "granular to 3 source frames (0.1 s at 30 fps).",
    "The system recommends a pause; it never actuates one. Any claim of saved filament is modelled "
    "from the detection frame, not measured on a printer.",
    "Confidence is a deterministic penalty product, not a calibrated probability; it should not be "
    "read as 'this many percent of such alerts are real'.",
    "No adversarial or occlusion cases are evaluated (a hand entering frame, the camera moving "
    "mid-print beyond the stabiliser's ±24 px clamp).",
]


def _check(result) -> list:
    if isinstance(result, dict):
        return result.get("errors", [])
    return list(result or [])


def check_threshold_flip() -> dict:
    """The REQ-F06 property case. Pure; no clip is decoded."""
    from app.agent import decide

    cfg = {"run_id": "flip", "source": "x", "backend": "baseline", "sample_every_n": 3,
           "max_frames": 300, "roi": None,
           "thresholds": {"warn": 0.45, "pause": 0.72, "confidence_floor": 0.55},
           "synthetic": True, "replay": False, "evidence_prefix": "flip"}

    def base(i: int, score: float) -> dict:
        return {"frame_index": i, "t_ms": i * 100, "first_layer_coverage": 0.90,
                "edge_regularity": 0.60, "motion_energy": 0.10, "texture_disorder": 0.10,
                "spaghetti_score": score, "confidence": 0.90, "roi": [0, 0, 10, 10],
                "backend": "baseline", "ops_ms": {}, "degraded": False}

    low = [base(i, 0.71) for i in range(3)]
    high = [base(i, 0.73) for i in range(3)]
    a_low = decide(low[-1], low[:-1], cfg)["action"]  # type: ignore[arg-type]
    a_high = decide(high[-1], high[:-1], cfg)["action"]  # type: ignore[arg-type]
    passed = (a_low != "request_pause_approval") and (a_high == "request_pause_approval")
    return {"observed": {"action_changes_at_threshold": passed, "action_below": a_low,
                         "action_above": a_high, "delta_in_score": 0.02},
            "passed": passed}


@contextlib.contextmanager
def apply_injection(name: str | None):
    """Context manager installing one fault. Restores the original on exit."""
    import unittest.mock as mock

    if not name:
        yield
        return
    if name == "degrade_every_frame":
        import app.vision.pipeline as pipe

        def fake(frame, state, cfg, backend, frame_index, t_ms):
            return {"frame_index": int(frame_index), "t_ms": int(t_ms),
                    "first_layer_coverage": 0.0, "edge_regularity": 0.0,
                    "motion_energy": 0.0, "texture_disorder": 0.0,
                    "spaghetti_score": 0.0, "confidence": 0.0,
                    "roi": [0, 0, 0, 0], "backend": "baseline",
                    "ops_ms": {}, "degraded": True}

        with mock.patch.object(pipe, "analyze_frame", fake):
            yield
    elif name == "raise_at_frame_30":
        import app.vision.pipeline as pipe

        real = pipe.analyze_frame

        def fake(frame, state, cfg, backend, frame_index, t_ms):
            if int(frame_index) == 30:
                raise RuntimeError("injected analysis failure")
            return real(frame, state, cfg, backend, frame_index, t_ms)

        with mock.patch.object(pipe, "analyze_frame", fake):
            yield
    elif name == "evidence_write_fails":
        from app.evidence.store import EvidenceStore

        def fake(self, key, data, content_type, kind="json"):
            return {"uri": "", "key": key, "kind": kind, "bytes": 0,
                    "backend": "local", "degraded": True}

        with mock.patch.object(EvidenceStore, "_put_bytes", fake):
            yield
    elif name == "approver_never_answers":
        import app.agent.loop as loop

        with mock.patch.object(loop, "APPROVAL_TIMEOUT_S", 1.0):
            yield
    else:
        yield


def _resolve_clip(case: dict, manifest: dict) -> tuple[str | None, bool, str | None]:
    """Returns (path, skipped, failure_reason)."""
    if case.get("clip") == "__fixtures_real__":
        d = os.path.join("fixtures", "real")
        try:
            mp4s = sorted(f for f in os.listdir(d) if f.endswith(".mp4"))
        except Exception:
            mp4s = []
        if not mp4s:
            if case.get("skip_if_missing"):
                return None, True, "no real footage present"
            return None, False, "no real footage present"
        return os.path.join(d, mp4s[0]), False, None
    for c in manifest.get("clips", []):
        if c["id"] == case.get("clip"):
            return c["path"], False, None
    return None, False, f"unknown clip {case.get('clip')}"


def run_case(case: dict, manifest: dict) -> dict:
    """Execute one case and return its `cases[]` entry. Never raises."""
    from app.config.settings import load_settings

    cid = case["id"]
    axis = AXES.get(cid, "task_effectiveness")
    try:
        if case.get("kind") == "property":
            r = check_threshold_flip()
            obs = r["observed"]
            ok = True
            reason = None
            for k, v in case["expect"].items():
                if obs.get(k) != v:
                    ok = False
                    reason = f"expected {k}={v}, observed {obs.get(k)}"
                    break
            return {"id": cid, "kind": case["kind"], "axis": axis,
                    "passed": ok and r["passed"], "skipped": False,
                    "observed": obs, "expected": case["expect"],
                    "failure_reason": reason, "asks": case.get("asks", "")}

        path, skipped, why = _resolve_clip(case, manifest)
        if skipped:
            return {"id": cid, "kind": case["kind"], "axis": axis,
                    "passed": False, "skipped": True, "observed": {},
                    "expected": case["expect"], "failure_reason": why,
                    "asks": case.get("asks", "")}
        if path is None:
            return {"id": cid, "kind": case["kind"], "axis": axis,
                    "passed": False, "skipped": False, "observed": {},
                    "expected": case["expect"], "failure_reason": why,
                    "asks": case.get("asks", "")}

        try:
            settings = load_settings()
        except Exception:
            settings = load_settings({})
        try:
            frames = next(c.get("frames", 300) for c in manifest.get("clips", [])
                          if c["id"] == case.get("clip"))
        except StopIteration:
            frames = 300
        cfg = {"run_id": f"eval-{cid}", "source": path, "backend": settings.backend,
               "sample_every_n": 3, "max_frames": frames, "roi": None,
               "thresholds": dict(settings.thresholds),
               "synthetic": (case["kind"] != "real"), "replay": False,
               "evidence_prefix": f"eval-{cid}"}

        envelopes: list[tuple] = []

        async def emit(step_id, status, payload, degraded):
            envelopes.append((step_id, status, payload, degraded))

        approver_called = {"n": 0}
        if case.get("inject") == "approver_never_answers":
            async def approver(d):
                approver_called["n"] += 1
                await asyncio.sleep(3600)
                return False
        else:
            async def approver(d):
                approver_called["n"] += 1
                return True

        from app.agent import run_agent

        with apply_injection(case.get("inject")):
            summary = asyncio.run(run_agent(cfg, emit, approver))  # type: ignore[arg-type]

        actions = Counter(d["action"] for d in summary.get("decisions", []))
        first_alert = summary.get("first_alert_frame")
        onset = case["expect"].get("onset_frame")
        if first_alert is not None and onset is not None:
            lat_frames = first_alert - onset
            lat_s = round(lat_frames / 30.0, 2)
        else:
            lat_frames, lat_s = None, None
        observed = {
            "pause_recommended": summary.get("pause_recommended"),
            "requires_human": any(d.get("requires_human") for d in summary.get("decisions", [])),
            "first_alert_frame": first_alert,
            "detect_latency_frames": lat_frames,
            "detect_latency_s": lat_s,
            "actions": dict(actions),
            "approvals": len(summary.get("approvals", [])),
            "approval_unanswered": any(a.get("approved") is False and a.get("resolved_at")
                                       for a in summary.get("approvals", [])),
            "evidence_uris": len(summary.get("evidence_uris", [])),
            "trace_steps": sum(1 for s, _, _, _ in envelopes
                               if s in ("perceive", "decide", "act")),
            "degraded": summary.get("degraded"),
            "completes": True,
        }
        # Observability artefacts for §5.4 (attached to the failure case run).
        observed["_envelopes"] = [(s, st) for s, st, _, _ in envelopes]
        observed["_decisions"] = summary.get("decisions", [])

        failures: list[str] = []
        for k, v in case["expect"].items():
            if k in ("pause_recommended", "requires_human", "completes", "degraded",
                     "approval_unanswered", "action_changes_at_threshold"):
                if observed.get(k) != v:
                    failures.append(f"expected {k}={v}, observed {observed.get(k)}")
            elif k == "max_action":
                limit = SEVERITY[v]
                bad = [a for a in actions if SEVERITY.get(a, 99) > limit]
                if bad:
                    failures.append(f"expected max_action={v}, observed {dict(actions)}")
            elif k == "min_action":
                floor = SEVERITY[v]
                if not any(SEVERITY.get(a, -1) >= floor for a in actions):
                    failures.append(f"expected min_action={v}, observed {dict(actions)}")
            elif k == "max_detect_latency_frames":
                if lat_frames is None or lat_frames > v:
                    failures.append(f"expected max_detect_latency_frames={v}, "
                                    f"observed {lat_frames}")
            elif k == "evidence_uris":
                if observed.get("evidence_uris") != v:
                    failures.append(f"expected evidence_uris={v}, "
                                    f"observed {observed.get('evidence_uris')}")
            elif k == "onset_frame":
                pass
            else:
                failures.append(f"unknown expect key {k}")
        passed = len(failures) == 0
        entry = {"id": cid, "kind": case["kind"], "axis": axis, "passed": passed,
                 "skipped": False, "observed": {k: v for k, v in observed.items()
                                                if not k.startswith("_")},
                 "expected": case["expect"],
                 "failure_reason": failures[0] if failures else None,
                 "asks": case.get("asks", "")}
        # Stash artefacts for observability checks without polluting the report.
        entry["_artefacts"] = {
            "envelopes": [(s, st, p) for s, st, p, _ in envelopes],
            "decisions": summary.get("decisions", []),
            "summary": {k: v for k, v in summary.items() if k != "decisions"},
        }
        return entry
    except Exception as err:
        logger.warning("eval: case %s raised (%s)", cid, type(err).__name__)
        return {"id": cid, "kind": case.get("kind", "?"),
                "axis": AXES.get(cid, "task_effectiveness"),
                "passed": False, "skipped": False, "observed": {},
                "expected": case.get("expect", {}),
                "failure_reason": f"case raised: {type(err).__name__}: {err}",
                "asks": case.get("asks", "")}


def _observability_checks(fail_entry: dict) -> dict:
    """§5.4 three checks over the failure-pauses-and-asks artefacts."""
    from app.agent import TOOLS
    from app.contracts.schemas import AGENT_DECISION_SCHEMA, RUN_SUMMARY_SCHEMA

    art = fail_entry.get("_artefacts", {})
    envs = art.get("envelopes", [])
    decisions = art.get("decisions", [])
    checks = {"traceable": False, "tools_recorded": False, "validates": False}
    try:
        perceive_frames = {p.get("scores", {}).get("frame_index")
                           for s, _, p in envs if s == "perceive" and isinstance(p, dict)}
        decide_frames = [p.get("decision", {}).get("frame_index")
                         for s, _, p in envs if s == "decide" and isinstance(p, dict)]
        checks["traceable"] = bool(decide_frames) and all(f in perceive_frames
                                                          for f in decide_frames)
    except Exception:
        pass
    try:
        tool_calls = sum(1 for s, _, _ in envs if s in ("perceive", "act"))
        checks["tools_recorded"] = tool_calls >= len(decisions) and len(decisions) > 0
    except Exception:
        pass
    try:
        from src.resilience import validate

        ok = True
        for d in decisions:
            if _check(validate(AGENT_DECISION_SCHEMA, d)):
                ok = False
        summ = dict(art.get("summary", {}))
        summ["decisions"] = decisions
        if _check(validate(RUN_SUMMARY_SCHEMA, summ)):
            ok = False
        checks["validates"] = ok and bool(decisions)
    except Exception:
        pass
    checks["tools_known"] = _tools_known()
    return checks


def _tools_known() -> bool:
    try:
        from app.agent import TOOLS

        return set(TOOLS) == {"probe_source", "detect_roi", "score_frame", "capture_evidence"}
    except Exception:
        return False


def render_markdown(report: dict) -> str:
    """§5.6 six sections."""
    L: list[str] = []
    total = len([c for c in report["cases"] if not c.get("skipped")])
    passed = sum(1 for c in report["cases"] if c.get("passed"))
    skipped = sum(1 for c in report["cases"] if c.get("skipped"))
    L.append("# Evaluation — Spaghetti Sentinel")
    L.append("")
    L.append(f"{passed}/{total} cases passed ({skipped} skipped).")
    L.append("")
    L.append("## Environment")
    L.append("")
    L.append("| fact | value |")
    L.append("|---|---|")
    for k, v in report["environment"].items():
        L.append(f"| {k} | {v} |")
    L.append("")
    L.append("## Results by axis")
    L.append("")
    weights = {"task_effectiveness": "Task effectiveness 20%",
               "failure_handling": "Failure handling 15%",
               "observability": "Observability (within 15%)",
               "human_control": "Human control (within 15%)"}
    for axis, vals in report["axes"].items():
        L.append(f"- {axis}: {vals['passed']}/{vals['total']} "
                 f"(score {vals['score']:.2f}) — {weights.get(axis, '')}")
    L.append("")
    L.append("## Cases")
    L.append("")
    for c in report["cases"]:
        L.append(f"### {c['id']} — {'PASS' if c.get('passed') else 'FAIL' if not c.get('skipped') else 'SKIPPED'}")
        L.append("")
        L.append(f"{c.get('asks', '')}")
        L.append("")
        L.append(f"expected: `{json.dumps(c.get('expected', {}))}`")
        L.append("")
        L.append(f"observed: `{json.dumps(c.get('observed', {}))}`")
        L.append("")
        if c.get("failure_reason"):
            L.append(f"failure: {c['failure_reason']}")
            L.append("")
    L.append("## Failure cases and limitations")
    L.append("")
    if report.get("failure_cases"):
        for f in report["failure_cases"]:
            L.append(f"- {f['id']}: {f['what_happened']} Why: {f['why']} "
                     f"Limitation: {f['limitation']}")
    else:
        L.append("Every case passed; the known limitations below still apply.")
    for lim in report.get("limitations", []):
        L.append(f"- {lim}")
    L.append("")
    L.append("## How to reproduce")
    L.append("")
    L.append("```bash")
    L.append("S3_BUCKET= python eval/run_eval.py --out eval/results")
    L.append("```")
    L.append(f"Commit: `{report.get('commit', 'unknown')}`")
    L.append("")
    return "\n".join(L)


def _git_commit() -> str:
    try:
        import subprocess

        return subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True).stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Spaghetti Sentinel evaluation")
    ap.add_argument("--cases", default="eval/cases.json")
    ap.add_argument("--out", default="eval/results")
    ap.add_argument("--only", default=None)
    ap.add_argument("--strict", action="store_true")
    args = ap.parse_args(argv)

    try:
        cases_doc = json.load(open(args.cases, encoding="utf-8"))
    except Exception as err:
        print(f"eval: cannot read case file {args.cases} ({err})")
        return 3
    try:
        manifest = json.load(open("fixtures/manifest.json", encoding="utf-8"))
    except Exception:
        manifest = {"clips": []}

    wanted = args.only.split(",") if args.only else None
    entries: list[dict] = []
    for case in cases_doc.get("cases", []):
        if wanted and case["id"] not in wanted:
            continue
        print(f"eval: running {case['id']} ...", flush=True)
        entries.append(run_case(case, manifest))

    # Axes.
    axes: dict[str, dict] = {}
    for axis in ("task_effectiveness", "failure_handling", "observability", "human_control"):
        ids = [c for c in entries if AXES.get(c["id"]) == axis and not c.get("skipped")]
        passed = sum(1 for c in ids if c.get("passed"))
        total = len(ids)
        axes[axis] = {"passed": passed, "total": total,
                      "score": round(passed / total, 3) if total else 1.0}

    # Observability: three §5.4 checks over the failure case artefacts.
    fail_entry = next((c for c in entries if c["id"] == "failure-pauses-and-asks"), None)
    obs_checks: dict = {}
    if fail_entry is not None and not fail_entry.get("skipped"):
        obs_checks = _observability_checks(fail_entry)
        obs_passed = sum(1 for v in obs_checks.values() if v)
        axes["observability"] = {"passed": obs_passed, "total": len(obs_checks),
                                 "score": round(obs_passed / max(1, len(obs_checks)), 3)}

    # Environment.
    try:
        from app.config.settings import load_settings

        settings = load_settings()
        backend_name = settings.backend
    except Exception:
        backend_name = "baseline"
    try:
        import cv2

        ocv = cv2.__version__
    except Exception:
        ocv = "unknown"
    try:
        from app.vision.backend import cool_version

        cool = cool_version()
    except Exception:
        cool = None
    import platform as _plat

    rationale_seen = ["fallback"]
    env = {"backend": backend_name, "opencv_version": ocv, "cool_version": cool,
           "arch": _plat.machine(), "rationale_source_observed": rationale_seen,
           "evidence_backend": "local", "synthetic_cases": 4, "real_cases": 0}

    failure_cases = []
    for c in entries:
        if not c.get("passed") and not c.get("skipped"):
            failure_cases.append({"id": c["id"],
                                  "what_happened": c.get("failure_reason") or "failed",
                                  "why": "see observed vs expected in Cases",
                                  "limitation": "recorded as a limitation for the report"})

    report = {
        "schema": "spaghetti-sentinel-eval-report/1.0.0",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "environment": env,
        "axes": axes,
        "cases": [{k: v for k, v in c.items() if not k.startswith("_")} for c in entries],
        "failure_cases": failure_cases,
        "limitations": LIMITATIONS,
        "commit": _git_commit(),
        "observability_checks": obs_checks,
    }

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "eval-report.json"), "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2)
        fh.write("\n")
    with open(os.path.join(args.out, "eval-report.md"), "w", encoding="utf-8") as fh:
        fh.write(render_markdown(report))

    total_n = len([c for c in entries if not c.get("skipped")])
    passed_n = sum(1 for c in entries if c.get("passed"))
    skipped_n = sum(1 for c in entries if c.get("skipped"))
    print(f"{passed_n}/{total_n} cases passed ({skipped_n} skipped).")
    if args.strict and any(not c.get("passed") and not c.get("skipped") for c in entries):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
